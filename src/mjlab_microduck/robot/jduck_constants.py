"""jduck robot constants (the user's UBT-12HC-servo biped, formerly MetalDuck).

The MJCF is generated by `rl_control/jduck_mjcf/build_mjcf.py` from
`rl_control/jduck_description/urdf/jduck_description.urdf`. It uses microduck's
naming (`trunk_base`, `left_hip_yaw`, ..., `left_foot_collision`, `passive_mouth`)
so the microduck velocity recipe can be reused.

Actuator. Default is the UBT-12HC FIRMWARE REPLICA (actuator/ubt12hc.py): it
copies the `pid_update()` law of `send_rev_230400_ult.ino` (pwm = clamp(|err|,
48, 255), deadband ±2 counts) and adds a DC motor using the URDF effort/velocity
(0.8 N·m, 3.0 rad/s). Not bench-identified yet, so the PWM→torque mapping is an
assumption. `JDUCK_ACTUATOR=pd` selects the old placeholder PD (kp=8, kd=0.2)
that jduck_walk_v0.onnx was trained with.
"""

import os
from pathlib import Path

import mujoco
from mjlab.actuator import BuiltinPositionActuatorCfg
from mjlab.entity import EntityArticulationInfoCfg, EntityCfg
from mjlab.utils.spec_config import CollisionCfg

from mjlab_microduck.actuator.ubt12hc import Ubt12hcActuatorCfg

# rl_control/jduck_mjcf — overridable for other checkouts.
_JDUCK_DIR = Path(
    os.environ.get(
        "JDUCK_MJCF_DIR",
        Path(__file__).resolve().parents[5] / "jduck_mjcf",
    )
)
JDUCK_WALK_XML: Path = _JDUCK_DIR / "robot_walk.xml"
JDUCK_SCENE_XML: Path = _JDUCK_DIR / "scene_walk.xml"


def get_jduck_walk_spec() -> mujoco.MjSpec:
    assert JDUCK_WALK_XML.exists(), (
        f"jduck MJCF not found: {JDUCK_WALK_XML} — run jduck_mjcf/build_mjcf.py"
    )
    return mujoco.MjSpec.from_file(str(JDUCK_WALK_XML))


JDUCK_ACTUATOR = os.environ.get("JDUCK_ACTUATOR", "ubt12hc")
assert JDUCK_ACTUATOR in ("ubt12hc", "pd"), JDUCK_ACTUATOR

# HOME. Measured in sim from the MJCF: trunk_base origin height with the soles on
# the floor. JDUCK_HOME=new|old overrides the default (new for ubt12hc, old for pd)
# so actuator and pose can be A/B'd separately.
JDUCK_HOME = os.environ.get("JDUCK_HOME", "new" if JDUCK_ACTUATOR == "ubt12hc" else "old")
assert JDUCK_HOME in ("new", "old"), JDUCK_HOME
if JDUCK_HOME == "new":
    # Knees bent the "other" way (hip_pitch −/+, knee +/−). Inside the friend's
    # measured ranges (jduck_tools/calibration.yaml), this pose needs only
    # ~0.10 N·m at the legs, below the firmware's 48-PWM floor (~0.15 N·m), and
    # leaves ~43° to the hip_pitch limit. The old HOME needed ~0.16 N·m: the
    # replica sagged ~17° and fell after ~1.2 s.
    JDUCK_HOME_TRUNK_Z = 0.157
    _LEGS = {
        r"left_hip_pitch": -0.25, r"right_hip_pitch": 0.25,
        r"left_knee": 0.25, r"right_knee": -0.25,
        r"left_ankle": 0.0, r"right_ankle": 0.0,
    }
else:
    # v0 HOME (what jduck_walk_v0.onnx was trained with). It sits 13–15° from
    # the hip_pitch limit.
    JDUCK_HOME_TRUNK_Z = 0.134
    _LEGS = {
        r"left_hip_pitch": 0.25, r"right_hip_pitch": -0.25,
        r"left_knee": -0.30, r"right_knee": 0.30,
        r"left_ankle": 0.05, r"right_ankle": -0.05,
    }

JDUCK_HOME_FRAME = EntityCfg.InitialStateCfg(
    pos=(0.0, 0.0, JDUCK_HOME_TRUNK_Z + 0.003),
    joint_pos={
        r".*hip_yaw.*": 0.0,
        r".*hip_roll.*": 0.0,
        **_LEGS,
        r".*neck_pitch.*": 0.0,
        r".*head_pitch.*": 0.0,
        r".*head_yaw.*": 0.0,
        r".*head_roll.*": 0.0,
        r"passive_mouth": 0.0,
    },
    joint_vel={".*": 0.0},
)

JDUCK_COLLISION = CollisionCfg(
    geom_names_expr=[".*_foot_collision"],
    condim={r"^(left|right)_foot_collision$": 3},
    priority={r"^(left|right)_foot_collision$": 1},
    friction={r"^(left|right)_foot_collision$": (1.0,)},
)

_SERVO_JOINTS = (r"^(?!passive_|trunk_base_freejoint$).*",)
# Stall torque. URDF/friend: 0.8 N·m. Official UBT-12HC spec (UBTECH Company
# Introduction p.16): 8 kg·cm @6.5 V, 12 kg·cm @8.5 V → ~0.96 N·m at the rated
# 7.4 V. JDUCK_TORQUE=<N·m> overrides it.
JDUCK_EFFORT_LIMIT = float(os.environ.get("JDUCK_TORQUE", "0.8"))
# URDF velocity (friend-confirmed). JDUCK_NOLOAD=<rad/s> overrides it for A/B;
# a large value (e.g. 1000) removes the torque–speed limit.
JDUCK_NO_LOAD_SPEED = float(os.environ.get("JDUCK_NOLOAD", "3.0"))
JDUCK_ARMATURE = 0.005       # guess; to be identified

# Firmware law: JDUCK_FW="K,FF,DB" → pwm = K*|err| + FF (floor 0), deadband DB.
# Unset = the CURRENT firmware (pwm = clamp(|err|, 48, 255), deadband 2).
# JDUCK_FW=orig = the stock firmware explicitly; "K,FF,DB,FLOOR" adds a pwm floor.
_fw = os.environ.get("JDUCK_FW")
if _fw == "orig":
    _fw = "1,0,2,48"
if _fw:
    _v = [float(x) for x in _fw.split(",")]
    _k, _ff, _db = _v[:3]
    _floor = _v[3] if len(_v) > 3 else 0.0
    JDUCK_FW_LAW = dict(pwm_per_count=_k, pwm_ff=_ff, pwm_min=_floor, deadband_counts=_db)
    JDUCK_FW_TAG = f"k{_k:g}ff{_ff:g}db{_db:g}" + (f"fl{_floor:g}" if _floor else "")
else:
    JDUCK_FW_LAW = dict(pwm_per_count=1.0, pwm_ff=0.0, pwm_min=48.0, deadband_counts=2.0)
    JDUCK_FW_TAG = "fwcur"
if os.environ.get("JDUCK_TORQUE"):
    JDUCK_FW_TAG += f"_t{os.environ['JDUCK_TORQUE']}"
if os.environ.get("JDUCK_NOLOAD"):
    JDUCK_FW_TAG += f"_w{os.environ['JDUCK_NOLOAD']}"
# JDUCK_QUANT=0 → continuous error instead of integer ADC counts (A/B only; the
# real firmware always sees integer counts).
JDUCK_FW_LAW["quantize"] = os.environ.get("JDUCK_QUANT", "1") != "0"
if not JDUCK_FW_LAW["quantize"]:
    JDUCK_FW_TAG += "_noquant"

if JDUCK_ACTUATOR == "ubt12hc":
    # Command delay: 1–3 physics steps (5–15 ms). The serial round trip for 14
    # servos at 230400 baud is ~10 ms.
    jduck_actuators = Ubt12hcActuatorCfg(
        target_names_expr=_SERVO_JOINTS,
        stiffness=0.0,
        damping=0.0,
        effort_limit=JDUCK_EFFORT_LIMIT,
        stall_torque=JDUCK_EFFORT_LIMIT,
        no_load_speed=JDUCK_NO_LOAD_SPEED,
        armature=JDUCK_ARMATURE,
        # JDUCK_FRICTION=<N·m>: gearbox Coulomb friction. 0.01 was a guess and made
        # the stock firmware impossible to hold still with (no policy, old HOME: falls),
        # while 0.05 already lets it sit quiet (leg |qd| 0.0015). Real geared hobby
        # servos are usually ≥0.05 N·m; measure it on the bench (calibrate.py).
        frictionloss=float(os.environ.get("JDUCK_FRICTION", "0.01")),
        delay_min_lag=1,
        delay_max_lag=3,
        **JDUCK_FW_LAW,
    )
else:
    jduck_actuators = BuiltinPositionActuatorCfg(
        target_names_expr=_SERVO_JOINTS,
        stiffness=8.0,
        damping=0.2,
        effort_limit=JDUCK_EFFORT_LIMIT,
        armature=JDUCK_ARMATURE,
        delay_min_lag=1,
        delay_max_lag=3,
    )

JDUCK_WALK_ROBOT_CFG = EntityCfg(
    spec_fn=get_jduck_walk_spec,
    init_state=JDUCK_HOME_FRAME,
    collisions=(JDUCK_COLLISION,),
    articulation=EntityArticulationInfoCfg(
        actuators=(jduck_actuators,),
        soft_joint_pos_limit_factor=0.9,
    ),
)
